#!/bin/bash
#
# Cross-compiles unudhcpd (vendored, patched copy in ./unudhcpd/ - see
# its README) using the same gcc-6-aarch64-linux-gnu toolchain container
# as build_kernel.sh, and installs it into debootstrap-rootfs as a
# systemd service bound to the rndis0 USB gadget netdev.
#
# Built as a normal dynamically linked binary: it only ever runs on the
# full Debian rootfs now, never from the initramfs (which just brings up
# the android_usb gadget itself - see initramfs/init), so there's no
# need for -static, and NSS-backed libc calls (getprotobyname() used to
# be one, see server.c) are actively unsafe when statically linked.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="$SCRIPT_DIR/unudhcpd"
CONTAINER_NAME="j4-gcc6"
ROOTFS_DIR="$SCRIPT_DIR/debootstrap-rootfs"

if [ ! -f "$SRC_DIR/main.c" ]; then
	echo "error: $SRC_DIR looks empty" >&2
	exit 1
fi
if [ ! -d "$ROOTFS_DIR" ]; then
	echo "error: missing $ROOTFS_DIR" >&2
	exit 1
fi

if ! docker container inspect "$CONTAINER_NAME" >/dev/null 2>&1; then
	echo "error: $CONTAINER_NAME container not found - run build_kernel.sh first to create it" >&2
	exit 1
fi
if ! docker ps --format '{{.Names}}' | grep -qx "$CONTAINER_NAME"; then
	echo "==> starting $CONTAINER_NAME container"
	docker start "$CONTAINER_NAME" >/dev/null
fi

VERSION="0.1-j4"

echo "==> building unudhcpd $VERSION (dynamic aarch64)"
docker exec "$CONTAINER_NAME" rm -rf /tmp/unudhcpd-build
docker cp "$SRC_DIR" "$CONTAINER_NAME:/tmp/unudhcpd-build"
docker exec -w /tmp/unudhcpd-build "$CONTAINER_NAME" aarch64-linux-gnu-gcc-6 \
	-O2 -Wall -DVERSION="\"$VERSION\"" \
	-o unudhcpd main.c server.c

mkdir -p "$SCRIPT_DIR/misc-files"
docker cp "$CONTAINER_NAME:/tmp/unudhcpd-build/unudhcpd" "$SCRIPT_DIR/misc-files/unudhcpd"
docker exec "$CONTAINER_NAME" rm -rf /tmp/unudhcpd-build

echo "==> installing into debootstrap-rootfs (/usr/local/sbin/unudhcpd)"
# A sudo prompt here is expected unless NOPASSWD sudo is already set up:
# debootstrap-rootfs is root-owned (see build_system_img.sh), so writing
# into it needs a real privilege escalation.
sudo install -o root -g root -m 755 "$SCRIPT_DIR/misc-files/unudhcpd" "$ROOTFS_DIR/usr/local/sbin/unudhcpd"

echo "==> installing unudhcpd.service"
sudo install -d -m 755 "$ROOTFS_DIR/etc/systemd/system"
sudo tee "$ROOTFS_DIR/etc/systemd/system/unudhcpd.service" >/dev/null <<'EOF'
[Unit]
Description=unudhcpd DHCP server for the USB (rndis0) tether interface
# sys-subsystem-net-devices-rndis0.device is auto-generated by udev/
# systemd for the rndis0 netdev, which the initramfs's android_usb
# gadget setup (see initramfs/init) creates or doesn't - it comes and
# goes with the USB cable, so bind to it rather than just starting at
# boot and hoping it's there.
BindsTo=sys-subsystem-net-devices-rndis0.device
After=sys-subsystem-net-devices-rndis0.device

[Service]
ExecStartPre=/sbin/ip addr replace 172.16.42.1/24 dev rndis0
ExecStartPre=/sbin/ip link set rndis0 up
ExecStart=/usr/local/sbin/unudhcpd -i rndis0 -s 172.16.42.1 -c 172.16.42.2
Restart=on-failure
RestartSec=1

[Install]
WantedBy=multi-user.target
EOF
sudo install -d -m 755 "$ROOTFS_DIR/etc/systemd/system/multi-user.target.wants"
sudo ln -sf /etc/systemd/system/unudhcpd.service "$ROOTFS_DIR/etc/systemd/system/multi-user.target.wants/unudhcpd.service"

echo "==> telling NetworkManager to leave rndis0 alone"
# unudhcpd.service owns rndis0's address (172.16.42.1, static) and runs
# its own DHCP server on it; NetworkManager would otherwise also try to
# manage it (e.g. autoconnect + DHCP client), fighting over the address.
sudo install -d -m 755 "$ROOTFS_DIR/etc/NetworkManager/conf.d"
sudo tee "$ROOTFS_DIR/etc/NetworkManager/conf.d/10-unmanaged-rndis0.conf" >/dev/null <<'EOF'
[keyfile]
unmanaged-devices=interface-name:rndis0
EOF

echo "==> done: $SCRIPT_DIR/misc-files/unudhcpd"
